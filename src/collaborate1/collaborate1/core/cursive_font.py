def _catmull_rom_segment(p0: Point2D, p1: Point2D, p2: Point2D, p3: Point2D, steps: int = 6) -> List[Point2D]:
    """4개 제어점 사이의 Catmull-Rom 스플라인 구간(p1 -> p2)을 샘플링한다."""
    pts: List[Point2D] = []
    for i in range(steps):
        t = i / steps
        t2 = t * t
        t3 = t2 * t
        x = 0.5 * (
            (2.0 * p1[0])
            + (-p0[0] + p2[0]) * t
            + (2.0 * p0[0] - 5.0 * p1[0] + 4.0 * p2[0] - p3[0]) * t2
            + (-p0[0] + 3.0 * p1[0] - 3.0 * p2[0] + p3[0]) * t3
        )
        y = 0.5 * (
            (2.0 * p1[1])
            + (-p0[1] + p2[1]) * t
            + (2.0 * p0[1] - 5.0 * p1[1] + 4.0 * p2[1] - p3[1]) * t2
            + (-p0[1] + 3.0 * p1[1] - 3.0 * p2[1] + p3[1]) * t3
        )
        pts.append((x, y))
    return pts


def _interpolate_stroke(ctrl: List[Point2D], steps_per_seg: int = 5) -> List[Point2D]:
    """제어점 리스트를 부드러운 곡선 폴리라인으로 보간한다."""
    if len(ctrl) <= 2:
        return list(ctrl)
    padded = [ctrl[0]] + list(ctrl) + [ctrl[-1]]
    out: List[Point2D] = []
    for i in range(1, len(padded) - 2):
        out.extend(_catmull_rom_segment(padded[i - 1], padded[i], padded[i + 1], padded[i + 2], steps_per_seg))
    out.append(ctrl[-1])
    return out


def _apply_calligraphy_thickness(pts: List[Point2D], thick_z: float, thin_z: float) -> List[Point3D]:
    """필기체 진행 방향(dy)에 따라 굵은 획(thick_z)과 얇은 획(thin_z)의 Z 오프셋을 부여한다."""
    if len(pts) <= 1:
        mid_z = 0.5 * (thick_z + thin_z)
        return [(p[0], p[1], mid_z) for p in pts]

    raw_z: List[float] = []
    for i in range(len(pts)):
        p_prev = pts[max(0, i - 1)]
        p_next = pts[min(len(pts) - 1, i + 1)]
        dx = p_next[0] - p_prev[0]
        dy = p_next[1] - p_prev[1]
        ds = math.hypot(dx, dy)
        # dy < 0 (아래로 내리는 획) -> ratio = -1.0 -> thick_z (2.0 mm)
        # dy > 0 (위로 올리는 획)   -> ratio = +1.0 -> thin_z  (3.0 mm)
        ratio = (dy / ds) if ds > 1e-6 else 0.0
        z_val = 0.5 * (thick_z + thin_z) + 0.5 * (thin_z - thick_z) * ratio
        raw_z.append(z_val)

    # 급격한 Z 변화를 방지하기 위해 인접 3점 이동 평균 스무딩 2회 적용
    smoothed = list(raw_z)
    for _ in range(2):
        nxt = [smoothed[0]]
        for i in range(1, len(smoothed) - 1):
            nxt.append((smoothed[i - 1] + 2.0 * smoothed[i] + smoothed[i + 1]) / 4.0)
        nxt.append(smoothed[-1])
        smoothed = nxt

    return [(pts[i][0], pts[i][1], smoothed[i]) for i in range(len(pts))]


def text_to_strokes(
    text: str,
    char_height_mm: float = 16.0,
    thick_z_mm: float = 2.0,
    thin_z_mm: float = 3.0,
    steps_per_seg: int = 4,
) -> List[List[Point3D]]:
    """문자열을 3D 필기체 획 리스트([[ (x, y, z_offset), ... ], ...])로 변환한다.

    인접한 글자의 끝점과 시작점이 (x, 0.25)로 일치하면 펜을 들지 않고 한 획으로 이어 쓴다.
    """
    strokes_2d: List[List[Point2D]] = []
    cursor_x = 0.0

    for ch in text:
        if ch not in CURSIVE_GLYPHS:
            continue
        adv, glyph_strokes = CURSIVE_GLYPHS[ch]
        if not glyph_strokes:
            cursor_x += adv * char_height_mm
            continue

        for s_idx, ctrl in enumerate(glyph_strokes):
            scaled = [(cursor_x + x * char_height_mm, y * char_height_mm) for x, y in ctrl]
            interp = _interpolate_stroke(scaled, steps_per_seg=steps_per_seg)

            # 이전 획의 끝점과 현재 획의 시작점이 거의 같으면 펜을 들지 않고 연속 연결
            if (
                s_idx == 0
                and strokes_2d
                and math.hypot(strokes_2d[-1][-1][0] - interp[0][0], strokes_2d[-1][-1][1] - interp[0][1]) < 0.8
            ):
                strokes_2d[-1].extend(interp[1:])
            else:
                strokes_2d.append(interp)

        cursor_x += adv * char_height_mm

    return [_apply_calligraphy_thickness(s, thick_z_mm, thin_z_mm) for s in strokes_2d]
